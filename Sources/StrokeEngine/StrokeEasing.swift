//
//  StrokeEasing.swift
//  模块：StrokeEngine（纯逻辑，不依赖 UI、网络或模型）
//
//  文件职责：把「一笔画了多久」换成「这一笔画到了百分之几」，中间加上起笔加速、
//  收笔减速。
//
//  为什么需要它（计划 A3，2026-08-29）：
//  在此之前一笔之内是**严格匀速**的——笔尖从落下那一刻就是全速，到终点又瞬间停住。
//  真人做不到这件事：手有质量，起笔要加速、收笔要减速。匀速的观感是「机器在描线」，
//  而且和 A5（收笔收到零宽）配合起来会更假：线宽在收细，速度却毫不减慢。
//
//  为什么用最小急动度（minimum jerk）而不是随便挑一条缓动曲线：
//  这是运动控制领域描述人类点到点运动的标准模型（Flash & Hogan, 1985）：人在把手
//  从一点移到另一点时，走的是让「加速度的变化率」总量最小的那条轨迹。
//  它的位置曲线正好是 10t³ − 15t⁴ + 6t⁵，两端的速度和加速度都为零——
//  也就是「从静止开始、到静止结束」，这恰好就是一笔的样子。
//
//  好处是它**一个参数都不需要**。随便挑一条 ease-in-out 曲线也能让线条不匀速，
//  但那就得回答「为什么是这条」，而这条曲线的答案是「因为人就是这么动的」。
//
//  只作用在笔**之内**：笔与笔之间的抬笔移动是另一件事（计划 A4 的 `pauseBefore`）。
//

import Foundation

nonisolated enum StrokeEasing {
    /// 最小急动度轨迹的位置曲线。
    ///
    /// - Parameter fraction: 这一笔的时间走过了百分之几（0…1，超出范围会被夹住）。
    /// - Returns: 这一笔的**长度**走过了百分之几。
    ///
    /// 性质（由 `StrokeEasingTests` 断言）：
    /// - `progress(0) == 0`，`progress(1) == 1`：起点终点必须精确对上，
    ///   否则笔画会缺一小截或者提前画完。
    /// - `progress(0.5) == 0.5`：曲线关于中点对称，加速和减速一样多。
    /// - 两端斜率为 0：起笔从静止开始，收笔停在静止。
    /// - 全程单调不减：笔尖不许倒退。
    static func progress(_ fraction: Double) -> Double {
        // 非有限值只可能来自上游的时钟异常。当成「还没开始」，
        // 而不是让 NaN 传进渲染层去污染整帧。
        guard fraction.isFinite else { return 0 }

        let t = min(1, max(0, fraction))
        // 10t³ − 15t⁴ + 6t⁵，按 t³ 提出公因式，减少一次乘法也更容易看出边界值。
        return t * t * t * (10 - 15 * t + 6 * t * t)
    }
}
